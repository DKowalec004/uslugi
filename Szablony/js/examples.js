window.applyExampleMode = function applyExampleMode() {
  const id = document.documentElement.dataset.template;
  const pack = id && window.EXAMPLES[id];
  document.documentElement.dataset.demo = '1';
  document.body.classList.toggle('is-demo', Boolean(pack));
  if (!pack) return;
  document.querySelectorAll('[data-fill]').forEach((el) => {
    const next = pack.fills && pack.fills[el.dataset.fill];
    if (next != null) el.innerHTML = next;
  });
  document.querySelectorAll('[data-img]').forEach((el) => {
    const src = pack.images && pack.images[el.dataset.img];
    if (src) el.style.setProperty('--img', "url('" + src + "')");
  });
  document.querySelectorAll('[data-ph]').forEach((el) => {
    const next = pack.placeholders && pack.placeholders[el.dataset.ph];
    if (next != null) el.setAttribute('placeholder', next);
  });
  document.title = pack.documentTitle;
  const theme = document.querySelector('[data-demo-theme]');
  if (theme) {
    theme.textContent = 'Przykład: ' + pack.theme;
    theme.hidden = false;
  }
};
